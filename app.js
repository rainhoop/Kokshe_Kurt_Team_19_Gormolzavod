let language = localStorage.getItem("kokshe-language") || "kk";
let toastTimer;

function translate(key, lang = language) {
  return copy[lang][key] ?? copy.kk[key] ?? key;
}

function loadCampaignState() {
  const stored = localStorage.getItem("kokshe-campaign");
  if (!stored) return { profile: null, codes: [] };
  try {
    const state = JSON.parse(stored);
    return {
      profile: state.profile || null,
      codes: Array.isArray(state.codes) ? state.codes : []
    };
  } catch (error) {
    console.error("Could not read saved campaign data.", error);
    showToast(language === "kk" ? "Сақталған мәліметтер оқылмады. Қайта енгізіп көр." : "Не удалось прочитать сохранённые данные. Введи их ещё раз.");
    return { profile: null, codes: [] };
  }
}

let campaign = loadCampaignState();

function saveCampaignState() {
  try {
    localStorage.setItem("kokshe-campaign", JSON.stringify(campaign));
    return true;
  } catch (error) {
    console.error("Could not save campaign data.", error);
    showToast(language === "kk" ? "Мәліметтерді сақтау мүмкін болмады. Браузер жадын тексер." : "Не удалось сохранить данные. Проверь хранилище браузера.");
    return false;
  }
}

function applyLanguage(nextLanguage) {
  if (!copy[nextLanguage]) return;
  language = nextLanguage;
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = translate(element.dataset.i18n);
    if (value.includes("<")) element.innerHTML = value;
    else element.textContent = value;
  });
  document.querySelectorAll("[data-alt]").forEach((image) => {
    image.alt = translate(image.dataset.alt);
  });
  document.querySelectorAll("[data-placeholder]").forEach((element) => {
    element.placeholder = translate(element.dataset.placeholder);
  });
  document.querySelectorAll(`[data-aria-${language}]`).forEach((element) => {
    element.setAttribute("aria-label", element.getAttribute(`data-aria-${language}`));
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    const selected = button.dataset.lang === language;
    button.classList.toggle("is-active", selected);
    button.setAttribute("aria-pressed", String(selected));
  });
  const packImage = document.querySelector("#pack-image");
  const isFront = document.querySelector(".pack-switch__button.is-active").dataset.pack === "front";
  packImage.alt = language === "kk"
    ? `Көкше Құрт орамасының ${isFront ? "алдыңғы" : "артқы"} беті`
    : `${isFront ? "Лицевая" : "Обратная"} сторона упаковки Көкше Құрт`;
  document.querySelector("#pack-zoom-image").alt = packImage.alt;
  try {
    localStorage.setItem("kokshe-language", language);
  } catch (error) {
    console.error("Could not save language preference.", error);
  }
}

function showToast(message) {
  const toast = document.querySelector("#toast");
  toast.textContent = message;
  toast.classList.add("is-visible");
  window.clearTimeout(toastTimer);
  toastTimer = window.setTimeout(() => toast.classList.remove("is-visible"), 4200);
}

function openRegistration(code = "") {
  const modal = document.querySelector("#register-modal");
  document.querySelector("#quick-code").value = code.toUpperCase();
  document.querySelector("#promo-code").value = code.toUpperCase();
  document.querySelector(".register-form").hidden = false;
  document.querySelector(".modal-success").hidden = true;
  document.querySelector(".form-feedback").textContent = "";
  if (!modal.open) modal.showModal();
  if (code) document.querySelector("#full-name").focus();
}

function normalizeCode(value) {
  return value.toUpperCase().replace(/\s+/g, "").trim();
}

function checkCode(code) {
  const normalized = normalizeCode(code);
  if (normalized.length < 4) {
    showToast(translate("msgCodeRequired"));
    return false;
  }
  if (campaign.codes.includes(normalized)) {
    showToast(translate("msgExisting"));
    return false;
  }
  showToast(translate("msgCodePending"));
  openRegistration(normalized);
  return true;
}

function registerCode(event) {
  event.preventDefault();
  const form = event.currentTarget;
  const data = new FormData(form);
  const name = String(data.get("fullName") || "").trim();
  const digits = String(data.get("phone") || "").replace(/\D/g, "");
  const city = String(data.get("city") || "");
  const age = String(data.get("age") || "");
  const code = normalizeCode(String(data.get("promoCode") || ""));
  const feedback = document.querySelector(".form-feedback");
  feedback.textContent = "";
  if (digits.length !== 11 || digits[0] !== "7") {
    feedback.textContent = translate("msgPhone");
    document.querySelector("#phone").focus();
    return;
  }
  if (!data.get("consent")) {
    feedback.textContent = translate("msgConsent");
    return;
  }
  if (code.length < 4 || campaign.codes.includes(code)) {
    feedback.textContent = code.length < 4 ? translate("msgCodeRequired") : translate("msgExisting");
    document.querySelector("#promo-code").focus();
    return;
  }
  if (!name || !city || !age) {
    feedback.textContent = translate("msgRegisterError");
    return;
  }
  const previous = campaign;
  campaign = {
    profile: { name, city, age },
    codes: [...campaign.codes, code]
  };
  if (!saveCampaignState()) {
    campaign = previous;
    return;
  }
  form.hidden = true;
  document.querySelector(".modal-success").hidden = false;
  document.querySelector("#promo-code").value = "";
  document.querySelector("#quick-code").value = "";
}

